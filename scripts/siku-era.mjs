const FILE = path.join(process.cwd(), "public/siku/catalog.json");
const checkOnly = process.argv.includes("--check");
const catalog = JSON.parse(fs.readFileSync(FILE, "utf8"));
const known = new Set(ERA_ORDER);

const needed = new Set(catalog.filter((e) => !e.bookId).map((e) => e.title));
const unmatched = Object.keys(ERA).filter((t) => !needed.has(t));
const missing = [...needed].filter((t) => !ERA[t]);
const badEra = Object.entries(ERA).filter(([, v]) => !known.has(v)).map(([k, v]) => `${k}→${v}`);
// 可读之书的代由抽取脚本所填，亦须在代序之内，否则长卷把它缀到卷尾去
const badRead = [...new Set(catalog.filter((e) => e.bookId).map((e) => e.dynasty))].filter((d) => !known.has(d));

const fail = [];
if (unmatched.length) fail.push(`表有目录所无之名 ${unmatched.length}：${unmatched.join("、")}`);
if (missing.length) fail.push(`目录有未断代之书 ${missing.length}：${missing.slice(0, 20).join("、")}${missing.length > 20 ? "…" : ""}`);
if (badEra.length) fail.push(`所断之代不在代序内：${badEra.join("、")}`);
if (badRead.length) fail.push(`可读书之代不在代序内：${badRead.join("、")}`);
if (fail.length) {
  for (const f of fail) console.error("✗ " + f);
  process.exit(1);
}

let filled = 0;
for (const e of catalog) {
  if (e.bookId) continue;
  const era = ERA[e.title];
  if (e.dynasty !== era) filled++;
  e.dynasty = era;
}
const tally = {};
for (const e of catalog) tally[e.dynasty] = (tally[e.dynasty] ?? 0) + 1;

console.log(`著录 ${catalog.length} 部：可读 ${catalog.filter((e) => e.bookId).length}，存目 ${needed.size}`);
console.log("各代部数：" + ERA_ORDER.map((d) => `${d} ${tally[d] ?? 0}`).join(" · "));
if (checkOnly) {
  console.log(`✓ 校验通过（--check，未改写；若改写将补 ${filled} 条）`);
} else {
  // 与抽取脚本同式：两格缩进、不转义汉字
  fs.writeFileSync(FILE, JSON.stringify(catalog, null, 2) + "\n", "utf8");
  console.log(`✓ 已补 ${filled} 条代入 public/siku/catalog.json`);
}
