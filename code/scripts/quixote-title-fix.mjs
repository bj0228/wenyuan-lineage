for (const [k, t] of Object.entries(TITLES)) {
  if (/第[一二三四五六七八九十百零\d]+章/.test(t)) bad.push(`题目${k}仍带章号: ${t}`);
}
for (let n = 1; n <= 126; n++) {
  const c = JSON.parse(readFileSync(join(DIR, `${n}.json`), "utf8")).content;
  if (/^#{1,6}\s/m.test(c)) bad.push(`ch${n} 正文仍有 # 行`);
  if (/\*\*/.test(c)) bad.push(`ch${n} 正文仍有 **`);
  if (/^-{3,}[ \t]*$/m.test(c)) bad.push(`ch${n} 正文仍有 ---`);
  if (!c.trim()) bad.push(`ch${n} 正文空了`);
}
console.log(`摘了题目行的章 (${cut.length}):`);
for (const l of cut) console.log("  " + l);
console.log(`正文清过残渣的章: ${residue.join(",")}`);
console.log(`残留单个 * 号: ${strayStars} 处（应为 0）`);
console.log(bad.length ? `✗ 自检未过:\n  ${bad.join("\n  ")}` : "✓ 自检通过：题目无章号、正文无 #/**/---、无空章");
