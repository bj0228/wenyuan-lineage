const meta = JSON.parse(readFileSync(join(DIR, "meta.json"), "utf8"));
const cut = []; // 摘掉了题目行的章
const residue = []; // 正文里清了残渣的章
let strayStars = 0;

for (let n = 1; n <= 126; n++) {
  const p = join(DIR, `${n}.json`);
  const j = JSON.parse(readFileSync(p, "utf8"));
  let c = j.content.replace(/^\s+/, "");

  // 摘章首题目行：顶头的 ###/##/# 行，或一行短而不断句、后头另起的话——
  // 全书 126 章里这样开的恰好都是题目（第 24 章「故事是这样说的：」以冒号断句，
  // 天然不算）。
  const firstLine = c.split("\n")[0].trim();
  const looksTitle =
    /^#{1,6}\s/.test(firstLine) ||
    (firstLine.length <= 100 && !/[。！？…”」：]$/.test(firstLine));
  if (looksTitle) {
    c = c.split("\n").slice(1).join("\n");
    cut.push(`${n}「${firstLine.slice(0, 30)}」`);
  }
  c = c.replace(/^\n+/, "");

  // 残渣与译名统一（题目进 meta，正文里那些 ### 歌名、** 加粗、--- 分隔线都拆掉，
  // 只留文字本身；同一人名书名前后不一的，并到正文通行的那种写法）
  const before = c;
  c = c
    // ch11 谣曲、ch14 牧歌、ch52 下卷献辞等——# 前缀摘掉，行后补一道空行，
    // 免得几行小标题挤进同一段（分段认的是空行）
    .replace(/^#{1,6}[ \t]*(.+)$/gm, "$1\n")
    .replace(/\*\*/g, "") // ch12/19/40/52/90/99 的加粗残字
    .replace(/^-{3,}[ \t]*\n?/gm, "") // ch52 的 --- 分隔线（连换行一并拿走）
    .replace(/《多此一问的奇案》/g, "《无谓的好奇》")
    .replace(/悲凄嬷嬷|悲戚嬷嬷/g, "悲苦嬷嬷")
    .replace(/贝内恩赫利/g, "贝嫩赫利")
    .replace(/曼查/g, "拉曼恰")
    .replace(/\n{3,}/g, "\n\n"); // 分隔线删净后收拢叠起来的空行
  if (c !== before) residue.push(n);
  strayStars += (c.match(/\*/g) || []).length;

  writeFileSync(p, JSON.stringify({ n: j.n, name: j.name, title: TITLES[n], content: c }, null, 1));
  meta.chapters.find((m) => m.n === n).title = TITLES[n];
}

writeFileSync(join(DIR, "meta.json"), JSON.stringify(meta, null, 1));

// —— 自检 ——
