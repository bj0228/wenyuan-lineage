#!/usr/bin/env node
/**
 * 成书之年 —— 给目录里考得出年份的书各系一个年，就地写进 catalog.json 的 `year` 字段。
 *
 * 为何只编一部分：`siku-era.mjs` 给一千零一十九部各断了一代，那是**必须**人人有的，
 * 因为长卷的横轴是代，无代便无处可落。年不同——年是**锦上添花**，考得出才写。
 * 给考不出的书编一个年，就是编造；目录上宁可留白，不可添一条伪据。此例与关系表
 * 「判据不全则不入表」、断代表「判据不全则不入代」同出一意。
 *
 * 年之两式：
 *
 *   "前赤壁赋": 1082          —— **定得到一年**：壬戌之秋，七月既望，赋中自记。
 *   "史記": [-104, -91]       —— **只定得到一段**：太初改历始撰，征和二年报任安书时已就。
 *
 * 一个数是一年，两个数是一段（含两端）。公元前作负数（前 91 年 = -91；无公元零年，
 * 故 -1 之后即 1）。不收者即「年未详」，上屏时那一处留空，不印一个问号。
 *
 * 取年之例：
 *
 *   一、**与断代同一口径**：取成书（撰成、奏进、刊行）之年，不取所记之时、所托之名。
 *       故《周易正义》取贞观十六年撰成至永徽四年颁定那一段，而非《周易》之年。凡断代表
 *       把某书断在本体一边者（如《三家注史记》断汉，不断三家注之唐），年亦取本体，两表相随。
 *   二、**单篇取撰作之年**：别集一类有百余部本是单篇，篇自有其年——《兰亭集序》
 *       永和九年（353）、《前赤壁赋》元丰五年（1082）、《李斯谏逐客书》秦王政十年（前 237）。
 *       文中无年、本传亦不系者（《爱莲说》《童心说》之属）不收。
 *   三、**只知其段者写段**：始撰与成书相去甚远者（《资治通鉴》治平三年始、元丰七年成）、
 *       或载籍只说「某某年间」者，一概写两个数，不取中数充作一年。
 *   四、**不可考者不收**：先秦诸子多非一时一手所成（《论语》《老子》《庄子》《山海经》），
 *       载籍无年、后人所推亦各不同，故一概不收——不收不是疏漏，是判据不足。
 *   五、**年须落在代内**：所系之年若不在断代表所断那一代的年限之内，即是两表有一处错，
 *       脚本报出不写。此校曾照出断代表一处讹误（《宋书》成于齐永明六年而旧断南朝梁）。
 *
 * 用法：node scripts/siku-year.mjs            （就地改写 public/siku/catalog.json）
 *       node scripts/siku-year.mjs --check    （只校验，不改写）
 *
 * 自校六事，任一不合即非零退出：表里有目录所无之名；豁免之书不在年表内；年式不合
 * （非整数、段之两端倒置、落在公元零年）；年超出目下合理之界（早于 -2000 或晚于今年）；
 * 年不在该书之代以内（`ERA_EXEMPT` 所列者除外）；豁免表有赘条（年本在代内，无须豁免）。
 *
 * 另有 `ERA_EXEMPT` 一表：目录于**人**的题署自有旧例（遗民不入新朝、历两代者从其仕宦
 * 之代），与「以成书之时为断」相违时两边都不改，别立豁免并说明其故，见该表之注。
 * 条例详见 docs/SIKU-YEAR-TABLE.md。
 *
 * 此脚本与 `siku-era.mjs` 一样**不得进 JS bundle**：它是生成目录的一道工序，不是运行时代码。
 */
